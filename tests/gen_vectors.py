"""Generate tests/vectors.h from the MicroPython reference implementation.

Runs src/benq_halo/utils.py on CPython (MicroPython-only decorators are stubbed),
so the C++ port in esphome/components/halo2 is tested against the original code.

    python3 tests/gen_vectors.py > tests/vectors.h
"""
import importlib.util
import pathlib
import sys
import types

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Stubs for MicroPython-only modules and decorators
micropython = types.ModuleType("micropython")
micropython.native = lambda f: f
micropython.viper = lambda f: f
sys.modules["micropython"] = micropython
config = types.ModuleType("config")
config.DEBUG = False
sys.modules["config"] = config
import builtins  # noqa: E402

builtins.micropython = micropython
builtins.ptr8 = lambda ba: ba

# Register-order address, as in halo2_address.py
HALO2_ADDRESS = [0x4E, 0xF5, 0x5D, 0x43]
addr_mod = types.ModuleType("halo2_address")
addr_mod.HALO2_ADDRESS = HALO2_ADDRESS
sys.modules["halo2_address"] = addr_mod

spec = importlib.util.spec_from_file_location("utils", ROOT / "src/benq_halo/utils.py")
utils = importlib.util.module_from_spec(spec)
spec.loader.exec_module(utils)

AIR = HALO2_ADDRESS[::-1]

PAYLOADS = [
    [0x04, 0x10, 0x0C, 0x0F, 0x55, 0x5B, 0x0F, 0x55, 0x01, 0x02],
    [0x02, 0x11, 0x0C, 0x0F, 0x55, 0x5B, 0x0F, 0x55, 0x01, 0x02],
    [0x03, 0x39, 0x64, 0x19, 0x64, 0x01, 0x19, 0x64, 0x01, 0x02],
    [0x00, 0x00, 0x01, 0x0A, 0x8C, 0x0A, 0x0A, 0x8C, 0x01, 0x02],
]


def arr(data):
    return "{" + ", ".join(f"0x{b:02X}" for b in data) + "}"


def main():
    out = []
    out.append("// Generated by tests/gen_vectors.py from src/benq_halo/utils.py. Do not edit.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append(f"static const uint8_t VEC_ADDRESS[4] = {arr(AIR)};")
    out.append("struct CompileVector { uint8_t pid; uint8_t payload[10]; uint8_t packet[14]; uint16_t crc; };")
    out.append("static const CompileVector COMPILE_VECTORS[] = {")
    for payload in PAYLOADS:
        for pid in range(4):
            pkt = utils.compile_packet(pid, payload)
            parsed = utils.parse_one_packet(bytearray(pkt))
            assert parsed["crc_valid"] and parsed["pid"] == pid and list(parsed["payload"]) == payload
            out.append(f"  {{{pid}, {arr(payload)}, {arr(pkt)}, 0x{parsed['crc']:04X}}},")
    out.append("};")

    # Address discovery capture: data after the discovery sync word, then a full packet
    # (preamble, address, PCF, payload, CRC), as received by the sniffer.
    pkt = utils.compile_packet(1, PAYLOADS[0])
    stream = bytearray([0x02, 0x12, 0x34, 0x00, 0x00, 0xAA]) + bytearray(AIR) + pkt
    stream += bytearray(36 - len(stream))
    utils.shift_left(stream)  # The sniffer sees it one bit earlier than byte aligned
    found = utils.extract_address(bytearray(stream))
    assert list(found) == AIR, found
    out.append(f"static const uint8_t DISCOVERY_CAPTURE[36] = {arr(stream)};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
